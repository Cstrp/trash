/**
 * Returns the result of concatenation of two strings.
 *
 * @param {string} str1
 * @param {string} str2
 * @return {string}
 *
 * @example
 *   'aa', 'bb' => 'aabb'
 *   'aa',''    => 'aa'
 *   '',  'bb'  => 'bb'
 */
function concatenateStrings(str1, str2) {
  let result = '';
  if (str1 !== '') {
    result += str1;
  }
  if (str2 !== '') {
    result += str2;
  }
  return result;
}

/**
 * Returns the length of given string.
 *
 * @param {string} str
 * @return {number}
 *
 * @example
 *   'aaaaa' => 5
 *   'b'     => 1
 *   ''      => 0
 */
const getStringLength = (str) => str.length;

/**
 * Returns the result of string template and given parameters firstName and lastName.
 * Please do not use concatenation, use template string :
 * https://developer.mozilla.org/en-US/docs/Web/JavaScript/Reference/template_strings
 *
 * @param {string} firstName
 * @param {string} lastName
 * @return {string}
 *
 * @example
 *   'John','Doe'      => 'Hello, John Doe!'
 *   'Chuck','Norris'  => 'Hello, Chuck Norris!'
 */
const getStringFromTemplate = (firstName, lastName) => `Hello, ${firstName} ${lastName}!`;

/**
 * Extracts a name from template string 'Hello, First_Name Last_Name!'.
 *
 * @param {string} str
 * @return {string}
 *
 * @example
 *   'Hello, John Doe!' => 'John Doe'
 *   'Hello, Chuck Norris!' => 'Chuck Norris'
 */
const extractNameFromTemplate = (str) => `${str.replace(/^Hello, /, '')
  .replace(/!$/, '')}`;

/**
 * Returns a first char of the given string.
 *
 * @param {string} str
 * @return {string}
 *
 * @example
 *   'John Doe'  => 'J'
 *   'cat'       => 'c'
 */

const getFirstChar = (str) => str.slice(0, 1);

/**
 * Removes a leading and trailing whitespace characters from string.
 *
 * @param {string} str
 * @return {string}
 *
 * @example
 *   '  Abracadabra'    => 'Abracadabra'
 *   'cat'              => 'cat'
 *   '\tHello, World! ' => 'Hello, World!'
 */
const removeLeadingAndTrailingWhitespaces = (str) => str.trim();

/**
 * Returns a string that repeated the specified number of times.
 *
 * @param {string} str
 * @param {string} count
 * @return {string}
 *
 * @example
 *   'A', 5  => 'AAAAA'
 *   'cat', 3 => 'catcatcat'
 */
const repeatString = (str, count) => `${str.repeat([count])}`;

/**
 * Remove the first occurrence of string inside another string
 *
 * @param {string} str
 * @param {string} value
 * @return {string}
 *
 * @example
 *   'To be or not to be', 'not'  => 'To be or  to be'
 *   'I like legends', 'end' => 'I like legs',
 *   'ABABAB','BA' => 'ABAB'
 */
function removeFirstOccurrences(str, value) {
  const idx = str.indexOf(value);
  if (idx === -1) {
    return str;
  }
  return str.slice(0, idx) + str.slice(idx + value.length);
}

/**
 * Remove the first and last angle brackets from tag string
 *
 * @param {string} str
 * @return {string}
 *
 * @example
 *   '<div>' => 'div'
 *   '<span>' => 'span'
 *   '<a>' => 'a'
 */

const unbracketTag = (str) => str.replace('<', '')
  .replace('>', '');

/**
 * Converts all characters of the specified string into the upper case
 *
 * @param {string} str
 * @return {string}
 *
 * @example
 *   'Thunderstruck' => 'THUNDERSTRUCK'
 *  'abcdefghijklmnopqrstuvwxyz' => 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
 */

const convertToUpperCase = (str) => str.toUpperCase();

/**
 * Extracts e-mails from single string with e-mails list delimeted by semicolons
 *
 * @param {string} str
 * @return {array}
 *
 * @example
 *   'angus.young@gmail.com;brian.johnson@hotmail.com;bon.scott@yahoo.com'
 *   => [
 *      'angus.young@gmail.com',
 *      'brian.johnson@hotmail.com',
 *      'bon.scott@yahoo.com'
 *   ],
 *   'info@gmail.com' => ['info@gmail.com']
 */
const extractEmails = (str) => str.split(';');

/**
 * Returns the string representation of rectangle with specified width and height
 * using pseudograhic chars
 *
 * @param {number} width
 * @param {number} height
 * @return {string}
 *
 * @example
 *
 *            '┌────┐\n'+
 *  (6,4) =>  '│    │\n'+
 *            '│    │\n'+
 *            '└────┘\n'
 *
 *  (2,2) =>  '┌┐\n'+
 *            '└┘\n'
 *
 *             '┌──────────┐\n'+
 *  (12,3) =>  '│          │\n'+
 *             '└──────────┘\n'
 *
 */

const getRectangleString = (width, height) => {
  const [top, bottom] = ['┌┐', '└┘'].map((item) => item[0] + '─'.repeat(width - 2) + item[1]);
  const middle = ['│', '│'].join(' '.repeat(width - 2));
  return `${[top, ...Array(height - 2)
    .fill(middle), bottom].join('\n')}\n`;
};

