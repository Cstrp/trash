function calculate(expression) {
	const arr = expression.split(' ')
	const result = []

	while (arr.length) {
		const elem = arr.pop()
		const num = Number(elem)
		if (!isNaN(num)) {
			result.push(num)
			continue
		}
		const fNum = result.pop()
		const sNum = result.pop()

		switch (elem) {
			case '+':
				result.push(fNum + sNum)
				break
			case '/':
				result.push(fNum / sNum)
				break
			case '-':
				result.push(fNum - sNum)
				break
			case '*':
				result.push(fNum * sNum)
				break
		}
	}
	return result[0]
}

console.log(calculate('+ 3 5'), 8)
console.log(calculate('* + 2 2 3'), 12)
console.log(calculate('/ + 3 5 * 2 2'), 2)
