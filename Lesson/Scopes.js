const a = 5; // note глобальная
function myFn () {
  //? область видимости для вложенной функции
  function innerFn () {
    //? внутренняя функция
    console.log(a);
  }
  innerFn(); // note не имеет глобальной области видимости, и может быть вызвана только внутри
}
myFn(); // ? все это цепочка видимости, данная функция должна вернуть undefined

