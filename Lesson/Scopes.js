function myFn () {
  let b; // ? локальная переменная
  a = true; // ? а не объявлена в зоне видимости функции, и данное значение присвается глобальной а
  b = 10;
  console.log(b); // ? область видимости функции
}

console.log(myFn()); // ? все описанное глобальная область видимости (вызов функции)

console.log(a); //? из области видимости функции (true)
